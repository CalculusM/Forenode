import numpy as np
from backtest_plan_actual import loo_prior, pct_err

# 협약축 2점(2003·2023) 사이 기하 보간✚ (CAGR 2.26%/년) — 실측 있는 연도만
PLAN = {2006: 66420, 2016: 83190, 2020: 91020, 2023: 97067}  # '06·'16·'20 보간✚
ACT = {2006: 51035, 2016: 82034, 2020: 75000, 2023: 74524}
#      '06 시의회 스니펫✚      '16 정점       '20 "약"✚     '23 경실련(보도 74%·직접 계산 76.8%)
RATIOS = {}
LEN_KM = 2.3
OPEN_YEAR = 2000

def main():
    pri = loo_prior('백양터널')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT.get(y)
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        b = p * m
        if a is None:
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    for y in sorted(RATIOS):
        r = RATIOS[y]
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        hit = lo <= r <= hi
        hits += hit; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / m - 1) * 100))
        print(f"{y:>5} {yr_n:>4} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} {(r/m-1)*100:>7.1f}% "
              f"{'적중' if hit else '미적중':>4}  ✚실현율만")
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n[관찰]')
    print('  · 25년 완결 1호의 생애주기 성적: 총사업비 893억 → 통행료수입 4,141억+(~20)+재정지원')
    print('    940억 — 도시터널 소액 사업의 수익 규모. 협약 눈높이(97,067 종점)는 끝내 미달(74~77%)')
    print('    이나 절대 수요는 정점 82,034까지 성장: "협약만 낙관, 사업은 성립"의 전형')
    print('  · ★수익률 실질 8.28% — 판결문 원문 확정(지자체 케이스 첫 수익률 확정). 우면산 11.36·')
    print('    거가 12.5·마창 8.86 주장과 함께 1기 지자체 상단 클러스터 보강')
    print('  · ★협약 운영비 814.5억(98 불변가) 원문 확보 — 협약 계획 운영비 자체를 확보한 첫 케이스:')
    print('    R6 실측과의 대사로 "운영비 오차A" 산출이 가능해짐 (DART 재무 확보 시 — Max20 과제)')
    print('  · 무료화 자연실험: +8~9%(시 예측 41%의 1/4) — 도시터널 요금 탄력의 하한 실증.')
    print('    인천대교(인하 후 초과 전환)와 양끝: 요금 이벤트 공변량은 시설유형과 교호작용')
    print('  · 재정지원 신청 vs 지급 감액 이력(신청 40~65억 vs 지급 21~39억) — 지급 산정 다툼이')
    print('    소송(2016구합20037)까지: 산식 검증 수요 실증 3호')
    print('  · 판결문(casenote) = 협약 원문 인용의 보고 — 협약일·수익률·MRG·총사업비·운영비·초기')
    print('    요금이 한 문서에: 소송 많은 노선은 판결문 우선 수집이 효율적(런북 반영 가치)')
    print('  · 보류: 실측 00~05·07~15·17~19·21~22(부산시 교통조사 페이지 ECONNREFUSED — 재시도)·')
    print('    재정지원 00~09·16~24 연도별·최종 누적 수입(~24)·특정감사 백양 몫·원협약(93 착공) 여부')

if __name__ == '__main__':
    main()
