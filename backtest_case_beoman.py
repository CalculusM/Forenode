"""
백테스트 케이스 #15 — 범안로 (대구동부순환도로(주))

계획(시의회 회의록·감사원 인용으로 확정): 1997 제1차 실시협약(월일 미상) · **사업수익률 9.44%
      (감사원: "MRG 90%까지 인정·수익률 9.44%까지 책정" — 벤치마크 상위권)** · 1차 변경
      2002.3.13 · 민간투자비 1,683억 · 유료 2001.9.24(삼덕 소형 500원)/2002.9.1(고모 600원) ·
      전 구간 1,100원 = km당 152원(시의회 — 고요금 논쟁) · 7.25km 도시고속화도로 · 대구시
재구조화: 2012.6 의결·7월 시행(제3차 변경) — MRG(보도상 추정수입 79.8% — 감사원 90%와
      상충: 최초 90%→변경 79.8% 추정, 병기)→비용보전(SCS): 투자원금+상환이자+운영비 대비
      미달분만. 예상지원 4,498→2,448억 = **절감 2,050억** · 보장 이자율 4.8%로 조정 ·
      감사원 과다지급 201억 환수·재협상 주문 + 행자부 표창 건의("모범사례"의 실체)
완결 임박: **2026.8.31 만료 → 9.1 전면 무료화 확정 — 24년 완결 2호** · 공단 이관(연 100억 절감)
실제: 실측 3점 — 개통 2002년 22,715 → 2016년 4만+✚ → 2025년 50,643 (**25년간 2.2배 성장 —
      도시권 성장 회복 3호**) · 실현율 비율 증거: 27.5%(2015 보도·귀속 연도 미상)·30%(2014
      시의회, 감사원 인용·시점 미상) — **연도 미상이라 채점 제외(참고)** ·
      재정지원 연도별 14개년: '03 34·'04 121·'10 189·'14 180·'16~'25(130/95/86/141/122/116/
      151/202/180/185) · **누적 3,204억('26.2) = 민간투자비의 190% — 보장 극단 경신(미시령 165%)**
      · 개통~2012 지급분 중 **1,450억이 이자**(시의회 시장 답변 — 고금리 구조 실증)
특이: 표본 외 홀드아웃 7번째(대구시) · 도시고속화도로(도시권 그룹 4호) · casenote 판결문 루트
      이 케이스에선 실패(수익률은 시의회 회의록이 대체 — 지자체 소스 위계: 회의록>보도)
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

PLAN = {}
ACT = {}
RATIOS = {}
LEN_KM = 7.25
OPEN_YEAR = 2002

def main():
    pri = loo_prior('범안로')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT.get(y)
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        b = p * m
        if a is None:
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    for y in sorted(RATIOS):
        r = RATIOS[y]
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        hit = lo <= r <= hi
        hits += hit; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / m - 1) * 100))
        print(f"{y:>5} {yr_n:>4} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} {(r/m-1)*100:>7.1f}% "
              f"{'적중' if hit else '미적중':>4}  ✚실현율만")
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('  (채점 불가 — 협약축 절대치·비율 귀속 연도 모두 미상: 참고 프로파일만 기록)')
    print('  참고: 실측 22,715(02)→~40,000(16)→50,643(25) · 실현율 27.5%(연도 미상)·30%(감사원 인용)')

    print('\n[관찰]')
    print('  · 교통량 채점 0점 처리 — 비율(27.5%·30%)의 귀속 연도 미상: R 규칙(추정·배정 금지)의')
    print('    정직 적용. 최병두(2007) 논문에 계획 교통량 표 존재 유력 — 수동 확보 시 재채점')
    print('  · 보장 극단 경신: 재정지원 누적 3,204억 = 민간투자비 1,683억의 190% (미시령 165%↗).')
    print('    그중 1,450억이 이자 — 고금리 자본구조가 보전금을 증폭시키는 메커니즘의 직접 증언')
    print('  · 수익률 9.44%+MRG 90%(최초) — 1기 지자체 상단 클러스터(우면산 11.36·거가 12.5) 재확인.')
    print('    2012 SCS 전환으로 절감 2,050억 + 감사원 201억 환수 주문 — "검증이 돈을 회수한" 실증')
    print('  · 도시권 성장 회복 3호: 개통 27.5%급에서 25년간 2.2배(50,643) — 마창·일산과 동일 패턴.')
    print('    도시권 공변량 = 낮은 초기 + 장기 성장 기울기의 조합으로 모델링해야 함을 3케이스가 수렴')
    print('  · 무료화 직전 재정지원이 최대(23년 202억) — 수요 성장에도 SCS 보전이 줄지 않는 구조:')
    print('    비용보전의 "운영비+이자" 앵커가 수요와 독립적이기 때문(거가와 동일 메커니즘)')
    print('  · 지자체 소스 위계 확립: 시의회 회의록(감사원 인용) > 보도 — 수익률·MRG·환수액이 회의록')
    print('    한 문서에서 확정. casenote 실패 시의 대체 루트로 런북 반영')
    print('  · 보류: 협약축(최병두 2007 PDF 수동 — TLS 차단)·재정지원 05~09·11~13·15·통행료수입')
    print('    누적·DART 재무·MRG 90 vs 79.8 상충 규명')

if __name__ == '__main__':
    main()
