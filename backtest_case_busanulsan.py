import numpy as np
from backtest_plan_actual import loo_prior, pct_err

PLAN = {2022: 64249, 2023: 65050, 2024: 65609}   # 표5-11
ACT = {2022: 43818, 2023: 45624, 2024: 44915}
RATIO_2016 = 0.558                                # 국토부 자료 보도 ✚비율만

CASH_OPEX = {2018: 425.4, 2019: 240.9, 2020: 248.4, 2021: 260.0,
             2022: 270.2, 2023: 354.8, 2024: 288.9}   # R6 (매출원가+판관비-무형순-유형감가)
TOLL_REV = {2018: 660.1, 2019: 676.2, 2020: 647.9, 2021: 685.1,
            2022: 703.4, 2023: 703.5, 2024: 701.0}
SUBSIDY = {2023: 182.1, 2024: 301.7}              # 정부재정지원금(영업외, 주석8)
CLAWBACK = {2018: 34.9, 2019: 14.2, 2020: 12.6, 2021: 5.4,
            2022: 5.3, 2023: 7.3, 2024: 13.9}     # 국고환수준비금전입액
LEN_KM = 47.2

def main():
    pri = loo_prior('부산-울산')
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[LOO prior — 부산-울산 제외] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode LOO P50(B) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B:P50':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT[y]
        b = p * mu
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = p10r <= a / p <= p90r
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    r = RATIO_2016
    hit16 = p10r <= r <= p90r
    print(f"{2016:>5} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} "
          f"{(r/mu-1)*100:>7.1f}% {'적중' if hit16 else '미적중':>4}  ✚실현율만(55.8%)")
    hits += hit16; n += 1
    eA.append(abs((r - 1) * 100)); eB.append(abs((r / mu - 1) * 100))
    print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n' + '=' * 96)
    print('표② 운영비 — 협약 계획 미공개(A 불가) · Forenode 통계모드(B) vs 실측')
    print('=' * 96)
    import opex_estimator
    act5 = float(np.mean([CASH_OPEX[y] for y in range(2020, 2025)]))
    est = opex_estimator.estimate_opex_series('BTO', annual_revenue_억=690.0, operation_years=30,
                                              terrain='산지', tunnel_ratio=0.15, bridge_ratio=0.15,
                                              growth_rate=0.005, inflation=0.0, road_length_km=LEN_KM)
    b_opex = float(np.mean(est['opex_series_억']))
    print(f"  실측 현금 OPEX('20~'24 평균): {act5:.0f}억/년 · 원단위 {act5/LEN_KM:.1f}억/km/년")
    print(f"  Forenode 통계모드: {b_opex:.0f}억/년 → 오차B {pct_err(act5, b_opex):+.1f}%")
    if est.get('warning'):
        print(f"  ⚠ L3 크로스체크: {est['warning']}")

    print('\n[관찰]')
    print('  · Forenode 우위 복귀(하위 실현율 노선): MAE 34.4→19.9%, 밴드 4/4 — 실현율 55.8~70.1%가')
    print('    밴드(56~108%) 안. 단 2016(55.8%)은 하한 55.7% 바로 안쪽 — 대구부산(50~58%)과 함께')
    print('    하위꼬리 두께의 경계 사례')
    print('  · ★통계모드 방향 반전: +21.0% 과소 (5연패는 -32~-66% 과대) — 매출비례는 요금 수준의')
    print('    함수(고요금 과대·저요금 과소)라는 L3 진단의 결정적 실증. L3 경고 미발동(원단위 5.0억/km')
    print('    벤치마크 내)도 정합 — 저요금 노선에선 걸러지지 않음: 원단위 기반 재설계 근거 완성')
    print('  · BTO-a 원형의 실측 재정 프로파일: 수요 68~70%인데 재정지원은 FY23~24에야 발생(302억) —')
    print('    MRG(수입 % 보장)였다면 매년 수백억. 위험분담 설계가 재정 노출을 어떻게 바꾸는지의')
    print('    정량 비교 소재 (vs 서울외곽 90% 고정보장 연 400억+)')
    print('  · 수익률 하한 케이스: 세전 4.74%/세후 4.21% + 자기자본 6~8% 밴드 — 협약수익률 벤치마크')
    print('    분포의 하한 앵커 + 양방향(보전/환수) 대칭 설계의 유일 사례')
    print('  · 국고환수준비금 전입 매년 5~35억 — 8% 초과 환수 대비 적립: 협약 종료 시 전체 정산 구조')

if __name__ == '__main__':
    main()
