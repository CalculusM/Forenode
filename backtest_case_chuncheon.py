import numpy as np
from backtest_plan_actual import loo_prior, pct_err

# 체제: '17~'19 = 최초협약 축(값 연속성 정황 — 판별 각주), '22~'24 = 변경협약('20.12) 축
PLAN_INITIAL = {2017: 55915, 2018: 56303, 2019: 57801}
ACT_INITIAL = {2017: 50724, 2018: 53347, 2019: 57665}
PLAN_V2020 = {2022: 60903, 2023: 61322, 2024: 62246}
ACT_V2020 = {2022: 62720, 2023: 60712, 2024: 64834}
RATIO_2021 = 1.026  # census — 절대값 미보유 ✚
RATIO_2020 = 0.994  # MKIF 재구조화 공시: '20.3Q 누적 일평균 59,636대 = 협약대비 99.4% ✚(연간 아님)

LEN_KM = 61.4

def main():
    pri = loo_prior('서울-춘천')
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[LOO prior — 서울-춘천 제외] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode LOO P50(B) vs 실측  [R1 부칙: 협약 체제별 구간 분리]')
    print('=' * 96)
    print(f"{'연도':>5} {'체제':>6} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B:P50':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    rows = [(y, PLAN_INITIAL[y], ACT_INITIAL[y], '최초') for y in sorted(PLAN_INITIAL)] + \
           [(y, PLAN_V2020[y], ACT_V2020[y], '변경20') for y in sorted(PLAN_V2020)]
    for y, p, a, regime in rows:
        b = p * mu
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = p10r <= a / p <= p90r
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {regime:>6} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    for yy, r, tag in [(2020, RATIO_2020, '✚실현율만(99.4%·3Q누적)'), (2021, RATIO_2021, '✚실현율만(102.6%)')]:
        regime = '최초' if yy == 2020 else '변경20'  # '20은 12.24 인하 전 = 최초축
        hit_r = p10r <= r <= p90r
        print(f"{yy:>5} {regime:>6} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} "
              f"{(r/mu-1)*100:>7.1f}% {'적중' if hit_r else '미적중':>4}  {tag}")
        hits += hit_r; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / mu - 1) * 100))
    print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")
    print("  ▶ 구간별: 최초협약축 A "
          f"{np.mean(eA[:3] + eA[6:7]):.1f}% vs B {np.mean(eB[:3] + eB[6:7]):.1f}% (4개년) · "
          f"변경협약축 A {np.mean(eA[3:6] + eA[7:]):.1f}% vs B {np.mean(eB[3:6] + eB[7:]):.1f}% (4개년)")

    print('\n[관찰]')
    print('  · 성숙기(9년차~) 실현율 90.7→94.7→99.8→99.4→102.6→103.0→99.0→104.2% — 8개년 연속 밴드')
    print('    적중이자 협약 수렴. 최초협약축 자체가 성숙기에 정확했던 낙관편향 분포의 우측 반례')
    print('  · 단 개통 초기(09~12) 실현율 ~50% 미달로 MRG 50%컷 논쟁 있던 노선 — 초기 축·실측 확보 시')
    print('    "램프업만 틀리고 성숙기는 맞은" 전형 프로파일 완성 (초기군 prior 필요성의 반대측 근거)')
    print('  · 협약(A) MAE 3.3% vs P50(B) 23.5% — V-005와 동일하게 정확한 협약축에선 P50 하향 보정이')
    print('    유해. v2 공변량 "협약 세대·정확도 이력" 필요성 2연속 실증')
    print('  · MRG 15년 스텝다운(80/70/60)+50%컷+환수(MKIF 요약 140%·원문 % 미판독) — 원문 제49조로')
    print('    보장/환수 양방향 구조 확인.')
    print('    2018 자금재조달(-16.2%)→2020 재구조화(-28.1%) 2단 인하에도 실측이 협약을 초과: 수요')
    print('    탄력 실증(표4-15 시뮬레이션 예측과 정합)')
    print('  · 재무(R6)·수익률 재구성 보류 — DART FY09~24 수동 + 부록5·7(협약 예측축) 변경협약서 2건')
    print('    직링크 확보(다운로드 대기)')

if __name__ == '__main__':
    main()
