"""
백테스트 케이스 #10 — 거가대교 (지케이해상도로(주), 구 GK해상도로)

계획: 기존 실시협약('11.4 표기 — 최초 체결일 웹 수집 중): 통행료 10,000원(CPI 인상)·
      MRG 77.55%/20년·수익률 12.5% · 총사업비 1조4,469억 = 민간 9,969 + 재정 4,473 (census) ·
      개통 2010.12.13·유료화 2011.1.1 · 8.2km 해상 사장교+침매터널 · 주무관청 부산+경남 공동
재구조화: 2013.11.11 2차 변경실시협약 (MP-24-11 표2-4·2-5) — MRG 폐지→비용보전(투자비+운영비),
      수익률 12.5%→4.7%(변동 4.55%·고정 5.05%, 50:50), 관리운영권가치 1조5,948억(경상),
      출자자 대우건설 등 8사→KBGK사모신탁, 예상 재정지원 5조4,586→1,007억 = 절감 5조3,579억 ·
      재구조화 당시(2013) 통행량 협약 대비 70%
실제: 감사보고서 FY2018~24 로컬 6건 파싱(교차검증 통과) — 영업수익형 구조:
      통행료수익 694~760억 + 보조금수익(SCS 비용보전) 471~697억 = 수입의 40%+가 재정,
      무형상각 420.4억 정액 · subsidy_series 7개년 직접 확보
특이: 표5-11 표본 외(지자체) → 전체 62관측 prior 홀드아웃 (우면산에 이어 2번째) ·
      총공사비 뻥튀기 논란(경남신문)·부당이득 환수 요구(경실련) — 계획치 신뢰성 자체가 쟁점
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

# 협약축: '11 30,335(한산신문 "실시협약상")·'15 38,000(오마이뉴스, 차수 미상) — 사이 기하 보간✚
#   사업자 통행량 비공개('22 대법원 협약공개 조례 무효) → 전체 축 확보 불가 구조
PLAN = {2011: 30335, 2012: 32142, 2013: 34057, 2014: 36086, 2015: 38000}  # '12~'14 보간✚
# 실측: 부산일보 연간(만대) ÷ 일수 산술 환산 (보간 아님)
ACT = {2011: 21007, 2012: 20799, 2013: 22620, 2014: 24667, 2015: 25651}
ACT_REF = {2016: 25644, 2017: 25213, 2018: 23010, 2020: 22699}  # 협약축 없음 — 참고
# ※ '20 부산일보 별도 기사 일평균 23,488과 연간 환산 22,699 불일치(기준 차이) — 연간 환산 일관 채택

# R6 현금 OPEX = 영업비용 − 무형상각(420.4 정액) − 유형감가 (파서 그리드 손계산)
CASH_OPEX = {2018: 185.0, 2019: 286.0, 2020: 380.2, 2021: 336.7,
             2022: 199.0, 2023: 212.0, 2024: 243.3}
TOLL_REV = {2018: 744.0, 2019: 760.3, 2020: 730.3, 2021: 740.5,
            2022: 753.4, 2023: 694.3, 2024: 719.1}
SUBSIDY = {2018: 649.5, 2019: 600.8, 2020: 697.4, 2021: 520.5,
           2022: 471.0, 2023: 499.3, 2024: 475.7}   # 보조금수익(비용보전)
LEN_KM = 8.2
OPEN_YEAR = 2011  # 유료화 기준

def main():
    pri = loo_prior('거가대교')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT.get(y)
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        b = p * m
        if a is None:
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n' + '=' * 96)
    print('표② 운영비 — 협약 계획 미공개(A 불가) · Forenode 통계모드(B) vs 실측')
    print('=' * 96)
    import opex_estimator
    act5 = float(np.mean([CASH_OPEX[y] for y in range(2020, 2025)]))
    est = opex_estimator.estimate_opex_series('BTO', annual_revenue_억=730.0, operation_years=40,
                                              terrain='해상', tunnel_ratio=0.45, bridge_ratio=0.55,
                                              growth_rate=0.0, inflation=0.0, road_length_km=LEN_KM)
    b_opex = float(np.mean(est['opex_series_억']))
    print(f"  실측 현금 OPEX('20~'24 평균): {act5:.0f}억/년 · 원단위 {act5/LEN_KM:.1f}억/km/년")
    print(f"  Forenode 통계모드: {b_opex:.0f}억/년 → 오차B {pct_err(act5, b_opex):+.1f}%")
    if est.get('warning'):
        print(f"  ⚠ L3 크로스체크: {est['warning']}")

    print('\n[관찰]')
    print('  · 실현율 69.3%(11)→65.2%(15) — 개통 직후부터 램프업 없이 60%대 정체 후 2016 정점')
    print('    (25,644대)→감소: 거제 조선업 침체와 동행. 수요가 특정 산업(조선) 경기에 종속된')
    print('    단일 목적 노선의 전형 — v2 공변량 "배후 수요 구조" 소재')
    print('  · 보전금 교차검증 성공: 기사 2020년 700억 vs 감사보고서 보조금수익 697.4억,')
    print('    2024 예산 484→추경 416 vs 계상 475.7억 — 언론·예산·회계 3원 대사가 맞물림')
    print('  · 비용보전 전환 후에도 보전금 471~697억/년 = 통행료수입의 65~95%: MRG 폐지가')
    print('    재정 지출 소멸이 아니라 "수요 리스크→비용 리스크" 전환임의 실증 (예상 재정지원')
    print('    5.4조→1,007억 추산과 실제 지급 괴리 — 8년 누적 2,478억+α: 추산의 낙관성 검증 소재)')
    print('  · 원단위 극단 상단 33.4억/km/년(해상 사장교+침매터널, 7점 중 최고 — 최저 2.5의 13배):')
    print('    통계모드 +9.4%는 역대 최소 오차지만 우연 근사(고요금 과대편향 × 극단 원단위 상쇄).')
    print('    L3 경고 발동·실측조차 벤치마크(1~12) 밖 — 시설유형별 원단위 밴드 필요의 결정 실증')
    print('  · 데이터 접근성 자체가 리스크: 사업자 통행량 비공개, 2022 대법원이 협약공개 조례')
    print('    무효 판단 — 공적 대조군(Forenode)의 존재 이유를 보여주는 제도적 실증')
    print('  · 최초협약(2003) 조건 미확증: "90%/14.96%" 언급 vs 확보된 77.55%/12.5%(11.4 변경)')
    print('    — 차수 관계 규명 보류. 실측 19·21~24 연간치·보전금 잔여 연도 보류')

if __name__ == '__main__':
    main()
