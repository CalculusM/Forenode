import numpy as np
from backtest_plan_actual import loo_prior, pct_err

# 협약축 '09~'16 (NABO 표8) — 실측 '10~'18·'21 미확보 (MKIF 분기 IR 순회·OpenDART 경로)
PLAN_EARLY = {2009: 34779, 2010: 35425, 2011: 40492, 2012: 42430,
              2013: 44460, 2014: 46587, 2015: 48817, 2016: 51153}
ACT_EARLY = {}   # '09 부분연도 25,086은 참고만(채점 제외)

PLAN_LATE = {2020: 59840,                             # ✚보간 ('16 51,153→'22 64,608 CAGR 4.0%)
             2022: 64608, 2023: 66590, 2024: 68317}
ACT_LATE = {2020: 43144,                              # ✚출처 재확인 권장
            2022: 53154, 2023: 67964, 2024: 74108}
RATIO_2019 = 0.975                                    # 인천투데이 — 협약比 97.5% ✚단독출처

LEN_KM = 12.3
OPEN_YEAR = 2009  # 10.19 개통 — 2009는 부분연도

def main():
    pri = loo_prior('인천대교')
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[LOO prior — 인천대교 제외] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    # 연차별 prior: 1~3년차 초기군(P50 55%, 37~81%)
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 55% + 4년차~ LOO) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    rows = [(y, PLAN_EARLY[y], ACT_EARLY.get(y)) for y in sorted(PLAN_EARLY)] + \
           [(y, PLAN_LATE[y], ACT_LATE[y]) for y in sorted(PLAN_LATE)]
    for y, p, a in rows:
        yr_n = y - OPEN_YEAR + 1
        early = yr_n <= 3
        m, lo, hi = (E_MU, E_LO, E_HI) if early else (mu, p10r, p90r)
        b = p * m
        if a is None:
            print(f"{y:>5} {yr_n:>4} {p:>9,} {'—':>9} {'—':>8} {b:>9,.0f} {'—':>8} {'—':>5}  실측 미확보")
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    r = RATIO_2019
    hit19 = p10r <= r <= p90r
    print(f"{2019:>5} {11:>4} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} "
          f"{(r/mu-1)*100:>7.1f}% {'적중' if hit19 else '미적중':>4}  ✚실현율만(97.5%·단독출처)")
    hits += hit19; n += 1
    eA.append(abs((r - 1) * 100)); eB.append(abs((r / mu - 1) * 100))
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")
    print("  ※ '09 개통연도(10.19~) 평균 25,086 = 협약比 72.1% — 부분연도라 채점 제외(참고)")
    print("  ※ '20 협약 59,840은 ✚보간 · '22 협약 64,608 vs NABO 표8 64,908 (+300, 변경협약 세대 추정)")

    print('\n[관찰]')
    print('  · 통행료 63% 인하(23.10, 5,500→2,000원) 직후 82.3→102.1→108.5% 초과 전환 — 요금')
    print('    탄력의 극적 사례. 천안논산·대구부산(반값에도 54~65% 정체)과 대조: 회랑 대체재')
    print('    (영종대교·공항철도) 있는 단거리 교량은 요금이 수요를 직접 지배')
    print('  · 성숙기 실현율 97.5%(19)→72.1%(20 코로나)→82.3%(22)→108.5%(24) — 외생 충격과')
    print('    요금 정책이 만드는 변동폭 36%p: 단일 P50의 한계, 밴드 필요성의 교과서 사례')
    print("  · ★'24 108.5% > 상한 106.4% — 첫 상단 밴드 실패 (대구부산 하단 1/7과 대칭 완성):")
    print('    요금 63% 인하가 협약축 리셋 없이(추정) 수요만 끌어올린 케이스 → v2 공변량에')
    print('    "요금 이벤트(인하율)" 추가 근거. 협약축 세대는 협약서 OCR로 확정 과제')
    print('  · MRG 80% 보장·120% 환수(15년, 24.10 만료) — 25년 1~9월에도 보전 203억(전국 최다,')
    print('    만료 정산 추정): 보장 만료 후 잔여 지급 확인 필요')
    print('  · 협약서 3종(최초 108p·1차 변경 175p·2차 16p) 확보 — 1차 변경이 최초보다 커')
    print('    전면 변경(수요·재무모델 갱신) 추정: 7.95%·협약축 세대 판별의 원문 근거 확보')
    print('  · 제3연륙교(청라~영종, 25 개통 예정) 손실보전 추정 5,900억 — 전향 리스크 관전점')
    print('  · 보류: 재무 전체(OpenDART)·실측 10~18·21(MKIF 분기 IR 순회)·MRG 연도별(국감 원자료)')

if __name__ == '__main__':
    main()
