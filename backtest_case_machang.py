# 협약축 4점: 2008 28,806·2009 29,946·2015 37,099(census 보도)·2018 40,000(idomin 연재)
# 실측 절대값: 2008 ~1.0만(근사✚)·2021 42,561(도의회)·2023 45,418·2024 47,745(공식 페이지 환산)
# 채점은 비율 5점: census 보도 4점(✚) + 2021 도의회 1차 소스. '23~'24는 협약축 없음(외삽 금지) — 참고
RATIOS = {2008: 0.353, 2010: 0.473, 2014: 0.724, 2015: 0.865, 2021: 0.894}
LEN_KM = 8.7   # 접속도로 포함 사업 연장
OPEN_YEAR = 2008

def main():
    pri = loo_prior('마창대교')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'실현율':>7} {'오차A%':>8} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(RATIOS):
        r = RATIOS[y]
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        ea, eb = (r - 1) * 100, (r / m - 1) * 100
        hit = lo <= r <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {r*100:>6.1f}% {ea:>7.1f}% {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n[관찰]')
    print('  · 2008 실현율 35.3% < 초기군 하한 37% — **초기군 실패 2번째(우면산 26.3%에 이어,')
    print('    둘 다 도시권 시설)**: 시설유형 공변량의 표본 보강. 단 마창은 이후 89.4%까지 수렴')
