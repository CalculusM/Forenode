"""
백테스트 케이스 #12 — 미시령터널 (미시령동서관통도로(주))

계획: 총사업비 2,580억(민간투자비 964억) · 개통 2006.5.3 · 주무관청 강원도 ·
      MRG 30년(~2036): 기준통행량 연 735만7,680대(≈20,158대/일)·미달기준 79.8% —
      기준/추정 축 관계는 웹 수집으로 확정 · 협약수익률 미확인(수집 중)
외생 충격: 2017.6 서울양양고속도로 개통 → 수요 붕괴 — **경쟁 회랑 공변량(매핑 #2)의 극단 실증**
      실측: 서울양양 개통 전 평균 15,386 → 2019년 5,802대/일 (−62%, 뉴시스)
MRG 구조 확정(수집): 기준통행량 735만7,680대/년(≈20,158대/일)의 **79.8% = 보장선**(≈16,086대/일),
      30년(~2036). 기준통행량=협약 추정축 여부는 원문 미확인 — 채점은 기준통행량 대용축 ✚
손보금: '06~'20 누적 650억(도민일보 — 단편 합산 506억과 불일치: 산정 vs 실지급 차이 추정) ·
      '21 146.89·'22 157.03 산정 후 미지급 · '23~'25 미지급 누계 478억 ·
      '36까지 잔여 3,715억~ (도의회) — **30년 총 4,257억 전망 = 총사업비의 165% (보장 극단 신기록)**
분쟁(최고 가치): 유료도로법 개정('18.1, 3년 연속 70% 미만 시 협약 변경 가능)을 강원도가 소급 적용
      → 운영사(국민연금 대주주) 행정소송 → **춘천지법 위헌법률심판제청 인용 — 헌재 계류('25)**.
      국민연금 배임 우려로 재협상 소극적 · 도는 MCC 전환 검토(용역 1,000억 절감 추산)
수익률: 협약수익률 미확인(원문·보도 전무) — 국민연금 투자수익률 실적 5.1%/목표 7.1%(세계일보)·
      후순위 보장이자 최고 65% 언급만. 강원도 정보공개청구 경로
특이: 표본 외 홀드아웃 4번째(강원도) · 지자체 통행량 비공개 패턴 3번째(거가·마창'23前과 동류)
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

# 협약 추정축 전무 — MRG 기준통행량(20,158대/일 고정)을 대용축으로 ✚ (연도별 가변 여부 미확인)
PLAN = {2016: 20158, 2019: 20158}
ACT = {2016: 15386, 2019: 5802}  # '16은 "서울양양 개통 전 평균"으로 기술됨 ✚
LEN_KM = 15.7  # 사업 연장 (터널 3.7km 포함)
OPEN_YEAR = 2006

def main():
    pri = loo_prior('미시령터널')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT.get(y)
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        b = p * m
        if a is None:
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n[관찰]')
    print('  · 경쟁 회랑 붕괴 정량: 15,386 → 5,802대/일(−62%, 서울양양 개통) — 공변량 #2의 극단.')
    print('    핵심: 서울양양은 예측 시점에 이미 계획된 노선 — "계획 네트워크 미반영" 낙관편향의')
    print('    전형으로, v2 공변량이 사전에 잡을 수 있는 유형(예측 불가 외생이 아님)')
    print('  · 보장 극단 신기록: 30년 보전 전망 4,257억 = 총사업비 2,580억의 165% (우면산 51% 경신)')
    print('  · 제도 리스크 최전선: 유료도로법 소급 조항 위헌심판 헌재 계류 — 보전 산식·협약 변경의')
    print('    법적 불확실성이 헌재까지. ICC 중재(마창)에 이어 "검증·분쟁 대응 수요" 실증 2호')
    print('  · 지배구조 효과: 국민연금 대주주 → 배임 우려로 재협상 봉쇄 — 재구조화 성사 여부가')
    print('    수익률·재정보다 주주 구조에 좌우되는 사례 (서울외곽은 신규 투자자 진입으로 우회)')
    print('  · 손보금 산정 vs 실지급 불일치(650 vs 506억) — 지급 지연·미지급이 만드는 회계 격차:')
    print('    거가(과다편성→감액)와 함께 보전금 집행 데이터의 신뢰 한계 실증')
    print('  · 보류: 협약 추정축·수익률(강원도 정보공개청구)·실측 연도별(06~15·17~18·20~24)·')
    print('    손보금 연도별 분해 · 채점 2점은 기준통행량 대용축 ✚ — 원문 확보 시 재채점')

if __name__ == '__main__':
    main()
