"""
백테스트 케이스 #16 — 문학터널 ((주)문학개발, 군인공제회→칸서스)

계획(수집 회수 — 중단 워크플로 트랜스크립트에서 직접 추출): 총사업비 813억(민간 703억 군인공제회)
      · 실시협약 2002.1.9(디지털미추홀 — 개통 직전 시점이라 최종 확정협약 추정, 원협약 별도
      가능성✚) · 개통 2002.3.15·운영 2002.4.1 · 예측 50,210대/일(귀속 연도 미상) ·
      MRG 예상통행수입의 90% · 개통 통행료 소형 700원(문화대전 — 위키 600원과 상충 병기)
재구조화: 인천 3터널(만월·원적·문학) 일괄 MRG 폐지→SCS — **수익률 ~12% → 4.9%(확정)** ·
      **문학 재정절감 408억** · 전환 시점 상충: 인천in "2013" vs 인천투데이 "2015부터" vs
      원적·만월 변경협약 2014.4 — 병기(규명 과제)
완결: **2022.3.30 협약 종료 → 4.1 무료화·기부채납 — 20년 완결 3호** (백양·범안로에 이어)
실제: **개통 직후 20,268대 = 목표 대비 46%(문화대전 — 초기 실현율 확보)** ·
      2011.10 26,862대 = 52.2% · 재정지원: 개통 후 6년 매년 ~60억 · 누적 880억(~2018) ·
      "총 1천억 보조금"(인천in) = 총사업비의 108~123%
특이: 표본 외 홀드아웃 8번째(인천시) · 도시터널 **정체형**(46→52%, 20년 — 마창·일산·범안로의
      성장 회복형과 대조: 도시권 내 이질성) · 국토연구 89권 논문 PDF 로컬 확보
      (tool-results/webfetch-1784342165109-p59wj7.pdf — 3터널 재구조화 분석, 추출 과제)
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

PLAN = {}
ACT = {}
RATIOS = {2002: 0.46, 2011: 0.522}  # '02 개통 직후 46%(문화대전)✚ · '11.10 52.2%(언론)✚
LEN_KM = 1.5
OPEN_YEAR = 2002

def main():
    pri = loo_prior('문학터널')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT.get(y)
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        b = p * m
        if a is None:
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    for y in sorted(RATIOS):
        r = RATIOS[y]
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        hit = lo <= r <= hi
        hits += hit; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / m - 1) * 100))
        print(f"{y:>5} {yr_n:>4} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} {(r/m-1)*100:>7.1f}% "
              f"{'적중' if hit else '미적중':>4}  ✚실현율만")
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n[관찰]')
    print('  · 도시터널 "정체형" 프로파일: 46%(02) → 52.2%(11) — 20년간 6%p 성장에 그침.')
    print('    마창(35→89)·일산(50→103)·범안로(2.2배)의 성장 회복형과 대조 — 도시권 내 이질성:')
    print('    배후 개발(신도시·산업)이 없는 순수 시내 연결 터널은 회복 동력 부재')
    print('  · 2011 52.2% = LOO 밴드 하한(55%) 밖 — 하단 실패(도시터널 만성 저실현, 우면산과 동류).')
    print('    초기군(02 46%)은 적중: 연차별 prior의 방향 재확인')
    print('  · 인천 3터널 일괄 재구조화: 수익률 12→4.9%·문학 절감 408억 — 원적·만월(12→4.95%,')
    print('    MP-24-11 표2-6·7)과 함께 지자체 패키지 재구조화의 완결 사례군')
    print('  · 생애주기: 총사업비 813억 → 보조금 ~1,000억(108~123%) — 보장 극단 시리즈 4호')
    print('    (우면산 51%·미시령 165%·범안로 190%와 함께 "터널 소형 사업 = 보전 배율 상위" 패턴)')
    print('  · 20년 완결 3호 확보로 완결 사업 3종 세트(백양 25년·범안로 24년·문학 20년) — 전 생애')
    print('    주기 채점·운영비 오차A 산출의 표본군 완성(전부 DART 재무 확보가 관건 — Max20)')
    print('  · 보류: 실측 03~10·12~22 연도별·재정지원 연도별 분해·SCS 전환 시점 상충(13/14/15)·')
    print('    수입 20년 누적·국토연구 논문 PDF 표 추출(로컬 보유)·협약 원년(2002.1.9 이전) 여부')

if __name__ == '__main__':
    main()
