import numpy as np
from backtest_plan_actual import loo_prior, pct_err

PLAN = {2022: 69693, 2023: 71181, 2024: 72701}   # 표5-11
ACT = {2022: 81771, 2023: 81777, 2024: 82573}
RATIOS = {2018: 1.07, 2021: 1.131}               # 정책브리핑·현황보고서 ✚비율만
LEN_KM = 38.5
OPEN_YEAR = 2009

def main():
    pri = loo_prior('서수원-평택')
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[LOO prior — 서수원-평택 제외] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: LOO P50) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT[y]
        yr_n = y - OPEN_YEAR + 1
        b = p * mu
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = p10r <= a / p <= p90r
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    for y in sorted(RATIOS):
        r = RATIOS[y]
        yr_n = y - OPEN_YEAR + 1
        hit = p10r <= r <= p90r
        hits += hit; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / mu - 1) * 100))
        print(f"{y:>5} {yr_n:>4} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} {(r/mu-1)*100:>7.1f}% "
              f"{'적중' if hit else '미적중':>4}  ✚실현율만")
    print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n표② 통행료수입 — 협약(A) vs 징수 실적 (NABO 2025결산, 억원)')
    print('  연도  협약수입  징수수입  실현율   |  수입 prior(62.33%) 적용 시 오차B')
    REV = {2021: (987.06, 1007.05), 2022: (1008.16, 1050.81), 2023: (1086.83, 1071.19),
           2024: (1129.13, 1079.88), 2025: (1153.22, 1081.47)}
    for y, (pa, aa) in sorted(REV.items()):
        rr = aa / pa
        eb = (rr / 0.6233 - 1) * 100
        print(f"  {y}  {pa:>7.0f}  {aa:>7.0f}  {rr*100:>5.1f}%  |  {eb:+.1f}%")
    print('  ▶ 수입 오차A: +2.0 ~ −6.2% (협약 수입 예측이 근접) vs 수입 prior B: +50~+67% 대패')

    print('\n[관찰]')
    print('  · ★역대 최악 밴드 실패 0/5 — 실현율 107~117%가 LOO 상한(104%) 밖: 하향 보정 prior가')
    print('    초과 노선에서 전패. 상단 실패 누적 1(인천대교)→6건 — "낙관편향은 평균적 경향이지')
    print('    법칙이 아니다"의 정면 기록 = 2군(양방향 검증)의 존재 이유 그 자체')
    print('  · 인천대교 상단 실패는 요금 이벤트(63% 인하)였지만 서수원평택은 이벤트 없는 순수')
    print('    과소예측 — 배후 개발(동탄) 급성장 가설(공식 문헌 미확보): 상단 실패도 2유형')
    print('  · ★교통량 초과 ≠ 수입 초과: 통행료 동결로 23부터 수입 협약 미달 → 미인상분 보전 대상.')
    print('    초과 노선의 재정 귀결이 환수가 아니라 보전이라는 역설 — 교통량/수입 prior 분리')
    print('    (81.4% vs 62.33%) 설계의 결정적 실증 + 요금 경로가 제3의 오차원임을 증명')
    print('  · 수입 채점(표②): 협약 A +2~-6% 근접 vs 수입 prior 62.33% 적용 시 +50~67% 대패 —')
    print('    수입 prior도 초과 노선에서 상단 실패(교통량 prior와 동일 구조의 패배)')
    print('  · 순수 BTO(MRG·재구조화 무)의 깨끗한 대조군 + 협약서 원문 4연속 확보')
    print('  · 보류: 실측 09~21 연도별(현황보고서 연판·DART 수입 주석)·초과 전환 시점·협약 축')
    print('    (협약서 별표 미포함 — 1차 변경협약서 미다운로드)·개통 통행료·과소예측 공식 분석')

if __name__ == '__main__':
    main()
