"""
백테스트 케이스 #5 — 수도권제1순환 북부구간 일산-퇴계원 (서울고속도로(주))

계획: 사업기간 2001~2007(건교부 '07.12.21 보도 원문) · 개통 통행료 4,300원('07.12~'09.12 명시) ·
      협약수익률 불변 세후 8.51%/경상 12.19%(RR-25-10 표2-3·MP-24-11 표2-12 — 최초냐 '11변경이냐 판별 보류) ·
      투자비(계) 2조2,792억·건설보조금 25.2% (표2-3) — census 구분치(민자 1조7,789억+국고 7,944억)와
      합계 불일치(보상비 포함 여부 추정) → 구분 확정 보류 ·
      MRG 90% 20년간('06~'26) 조정 없이 유지 (MP-24-11 표1-3 — 타 노선 77~82% 하향과 대조)
재구조화(1호): 2018.3.29 기간연장+투자자변경 — 통행료 4,800→3,200원(-33%), 운영 '36→'56(+20년),
      기존기간 8.51% 유지+MRG 등 신규투자자 부담, 연장기간 2.74%(세전경상) 최소비용보전,
      사업권가치 2조3,053억(경상), 국민연금 86%→(연장기간) 미래에셋 60% (MP-24-11 표2-12)
실제: 감사보고서 FY2018~2024 로컬(R6 현금 OPEX·재정지원금 2018=413.9억/2019=18.7억) ·
      협약·실측 '22~'24(표5-11: 100.2/101.7/99.4%)·'21(현황보고서 101.8% ✚비율만) ·
      변경협약 예측축 표4-14(인하 후 '20 139,200 → '40 120,607) ·
      후순위차입 3,491억 금리 20~48%·FY2012 이자 1,849억(경향 2013.10.12) ·
      국고보조 5년('16~'20 추정) 누계 1,573억(홍기원 의원실 '21.10)

구간1(최초협약 vs 실제) 보류 — 최초협약 연도별 추정축·실측 '07~'21·수입 '06~'17 미확보.
  확보 경로: ① KOTI(2016) 『서울외곽 북부 민자구간 통행료 개선방안』 원문(p.70~71 표 존재 확인)
            ② 국토부 2016.12.5 보도 첨부 R1612120.hwp (KDI eiec num=160537 — hwp 수동 다운로드)
            ③ 실시협약 원문(국토부 공개게시판) · 통행료수입은 DART 감사보고서 2006~2017(수동 조회)
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

# ── 구간 1: 최초협약 체제 (2006.6~2018.3) — 보류 (독스트링의 확보 경로 3건) ──
PLAN_INITIAL = {}   # {연도: 협약 추정 대/일}
ACT_INITIAL = {}    # {연도: 실측 대/일}

# ── 구간 2: 변경협약 체제 (2018.3~) — 표5-11 + 현황보고서 ──
PLAN_V2018 = {2022: 135945, 2023: 137405, 2024: 138882}
ACT_V2018 = {2022: 136219, 2023: 139678, 2024: 138057}
RATIO_2021 = 1.018  # '21 실현율(현황보고서) — 절대값 미보유 ✚

CASH_OPEX = {2018: 299.7, 2019: 341.1, 2020: 348.9, 2021: 338.6,
             2022: 366.2, 2023: 385.1, 2024: 394.3}   # R6: 매출원가+판관비-무형상각-유형감가
TOLL_REV = {2018: 1580.9, 2019: 1526.2, 2020: 1513.0, 2021: 1571.4,
            2022: 1537.9, 2023: 1551.5, 2024: 1546.0}  # 통행료수입(재정지원 제외)
SUBSIDY = {2018: 413.9, 2019: 18.7}                    # 재정지원금액(주석7) — subsidy_series 실증례
LEN_KM = 36.3

def main():
    pri = loo_prior('서울외곽')
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[LOO prior — 서울외곽 제외] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode LOO P50(B) vs 실측  [R1 부칙: 협약 체제별 구간 분리]')
    print('=' * 96)
    print(f"{'연도':>5} {'체제':>6} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B:P50':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    rows = [(y, PLAN_INITIAL[y], ACT_INITIAL[y], '최초') for y in sorted(PLAN_INITIAL)] + \
           [(y, PLAN_V2018[y], ACT_V2018[y], '변경18') for y in sorted(PLAN_V2018)]
    for y, p, a, regime in rows:
        b = p * mu
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = p10r <= a / p <= p90r
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {regime:>6} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    if RATIO_2021:
        r = RATIO_2021
        hit21 = p10r <= r <= p90r
        print(f"{2021:>5} {'변경18':>6} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} "
              f"{(r/mu-1)*100:>7.1f}% {'적중' if hit21 else '미적중':>4}  ✚실현율만(101.8%)")
        hits += hit21; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / mu - 1) * 100))
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n' + '=' * 96)
    print('표② 운영비 — 협약 계획 미공개(A 불가) · Forenode 통계모드(B) vs 실측')
    print('=' * 96)
    import opex_estimator
    act5 = float(np.mean([CASH_OPEX[y] for y in range(2020, 2025)]))
    est = opex_estimator.estimate_opex_series('BTO', annual_revenue_억=1550.0, operation_years=30,
                                              terrain='산지', tunnel_ratio=0.25, bridge_ratio=0.10,
                                              growth_rate=0.005, inflation=0.0, road_length_km=LEN_KM)
    b_opex = float(np.mean(est['opex_series_억']))
    print(f"  실측 현금 OPEX('20~'24 평균): {act5:.0f}억/년 · 원단위 {act5/LEN_KM:.1f}억/km/년")
    print(f"  Forenode 통계모드: {b_opex:.0f}억/년 → 오차B {pct_err(act5, b_opex):+.1f}%")
    if est.get('warning'):
        print(f"  ⚠ L3 크로스체크: {est['warning']}")

    print('\n[관찰]')
    print('  · 재구조화 1호(18.3)의 협약 눈높이 리셋 실증: 변경협약 대비 실현율 99~102% 4연속 —')
    print('    "회복=협약 눈높이의 함수" 패턴의 결정판 (예측 축을 현실화하면 실현율은 100%에 붙음)')
    print('  · 밴드 상단 검증: 실현율 ~1.0이 LOO 밴드(54~106%) 상한 안쪽 — 4/4 커버. 단 P50(80.4%)은')
    print('    체계적 하향 → 재구조화 노선(협약 리셋)엔 P50 보정 없이는 협약(A)이 우위. v2 공변량')
    print('    "협약 세대(최초/재구조화 후)" 필요성의 첫 상단측 근거 (대구부산 하단측과 대칭)')
    print('  · MRG 90%·20년 무조정 + 후순위 20~48% — 최악 조합의 재정 유출: 통행료수입의 26%')
    print('    (2018년 414억)가 재정지원. 재구조화로 신규투자자 부담 전환 → 재정 절감 1.4조(국토부 공표)')
    print('  · 수입 1,550억/년 정체 vs 현금 OPEX 300→394억(+31%, 6년) — 수입 정체 국면에서 OPEX만')
    print('    상승하는 노후화 국면 진입. 원단위 9~11억/km/년은 대구부산(10.6)과 같은 상위 밴드')
    print('  · 구간1(최초협약 vs 실제)·수익률 재구성 보류 — 독스트링 경로 3건 (Max20 대량 수집 대상)')

if __name__ == '__main__':
    main()
