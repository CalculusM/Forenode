"""
백테스트 케이스 #9 — 우면산터널 (우면산인프라웨이(주), 구 우면산개발)

계획: 최초 협약수익률 11.36%(당초 — 22개 벤치마크 분포 최상단) → 2016.1 변경협약 향후 5.37%·
      전기간 8.95% (서울시 공식 보도) · 총사업비 ~1,402억 · MRG 85%·통행료 2,000원·운영 30년 ·
      개통 2004.1 · 주무관청 서울특별시 (첫 지자체 관할 케이스)
재구조화: 2016.1 — MRG 폐지→통행료수입 분할관리방식, 2,500원 2033까지 동결, 미지급 238억 소멸,
      수익률 시중금리 반영(향후 5.37%), 재정절감 1,587억(MRG 908+수입분할 잉여 679) +
      시민편익 1,027억 · 2015.8 교직원공제회 최대주주(MKIF 36% 유지) (서울시 공식 보도)
연혁: 착공 1997.12 · 개통 2004.1.6(소음 문제로 연기) · 통행료 2,000원 → 2011.12.17 2,500원 ·
      "2003년 협약" 표현(서울시 보도 — 변경협약 시사, 최초 체결일 미확인)
실제: 2004 예측 52,866 vs 실측 13,886 = 실현율 26.3% (역대 최악급 낙관편향) ·
      2014 예측 42,988 vs 실측 27,101 = 63.0% (2015 국감) · 2012 실측 25,105(연간 9,188천대÷366,
      협약축 없음 — 참고) · MRG '06 155억(개시)~'11 37억(마지막), 6년 누계 479억
특이: 표5-11 표본 외 노선 → prior = 전체 62관측 (LOO 아님 — 순환 없는 깨끗한 홀드아웃) ·
      2012 서울시의회 특위: 자본잠식·후순위 금리 ~20% 적발 (서울외곽 20~48%와 동일 패턴)
보류: 실측 전체 시계열 — 서울 열린데이터광장 '유료도로 통행료 수입 통계'(10200/S/2)가 공식
      보유처 확인(JS 렌더로 미열람 — 브라우저/API 키 경로) · 재무 — DART 우면산인프라웨이
      rcpNo 특정 후 뷰어 직접 · MKIF 1H2024 PDF 로컬 확보(텍스트 추출 실패 — pdfplumber 과제)
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

PLAN = {2004: 52866, 2014: 42988}   # '14 = 2015 국감 브리핑 (협약축 감소 곡선 — 기준 재확인 권장)
ACT = {2004: 13886, 2014: 27101}
ACT_REF_2012 = 25105                # 협약축 없음 — 참고만
LEN_KM = 2.9  # 터널 본선 (접속도로 제외)
OPEN_YEAR = 2004

def main():
    pri = loo_prior('우면산터널')  # 표본 외 → loo == 전체 62관측
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[전체 prior — 표본 외 홀드아웃] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")
    E_MU, E_LO, E_HI = 0.55, 0.37, 0.81  # 1~3년차 초기군

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: 1~3년차 초기군 + 4년차~ 전체 prior) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT.get(y)
        yr_n = y - OPEN_YEAR + 1
        m, lo, hi = (E_MU, E_LO, E_HI) if yr_n <= 3 else (mu, p10r, p90r)
        b = p * m
        if a is None:
            print(f"{y:>5} {yr_n:>4} {p:>9,} {'—':>9} {'—':>8} {b:>9,.0f} {'—':>8} {'—':>5}")
            continue
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = lo <= a / p <= hi
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {yr_n:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    if n:
        print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")
    print(f"  ※ 2012 실측 {ACT_REF_2012:,}대 — 협약축 미확보로 채점 제외(참고)")

    print('\n[관찰]')
    print('  · 2004 실현율 26.3% — 초기군 prior(55%, 밴드 37~81%)조차 크게 낙관: **초기군 밴드 첫 실패**.')
    print('    도시 단거리 유료터널(무료 대체로 존재)은 고속도로 램프업 분포와 다른 모집단 —')
    print('    v2 공변량 "시설 유형(도시터널/교량/고속도로)" 필요 근거')
    print('  · 그래도 B 방향은 옳음: 2004 오차 A -73.7% vs B -52.2%, 2014 A -37.0% vs B -22.5% —')
    print('    최악 낙관 케이스에서도 하향 보정이 오차를 15~21%p 줄임 (MAE 55.3→37.4%)')
    print('  · 수익률 11.36%(최상단) → 5.37% 재조정 — 협약수익률 분포의 상단 앵커. 후순위 ~20%')
    print('    구조 적발(2012 특위)까지 서울외곽과 동형: 고수익률+MRG+후순위 = 1기 표준 패턴')
    print('  · MRG 원단위: 총사업비 1,402억 사업에 MRG 479억 지급+238억 소멸 — 투자비 대비 51%가')
    print('    보장 청구로 전환된 극단 사례. 재구조화 절감 1,587억은 총사업비를 초과')
    print('  · 첫 지자체(서울시) 관할 케이스 — 국토부 축(현황보고서·RR-25-10)이 안 닿는 영역:')
    print('    열린데이터광장·시의회 특위·시 보도자료가 대체 소스로 실증됨')

if __name__ == '__main__':
    main()
