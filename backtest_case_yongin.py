"""
백테스트 케이스 #18 — 용인-서울 (경수고속도로(주)) · 2군 2호: "성공모델" 대조군

계획: 실시협약 2005.1.10(회사 공식) · 총사업비 1조5,256억(경수 투자 5,732억) · 22.9km ·
      개통 2009.7.1 · 국토부 · MRG 없음 · 2015 자금재조달 · 협약수익률 미확인
      (molit idx=242971 협약서 게시 확인 — 별표 문제로 보류, RR-24-12 54건 리스트 경로)
실제: 회사 공개 실측 — 39,005('09) → 95,431('20) → 97,042('22) · 수입 115억→562억 ·
      '18 87.5%(정책브리핑) · 표5-11 '22~'24: 82.4/82.2/82.1%
★수입 패널(NABO): 실현율 80.8('21)→74.7→69.9→67.3→62.5%('25) — **교통량 82%대 유지인데
      수입은 하락 일로(요금 1,800원 동결 vs 협약 2,200원)**: 수입-교통량 격차 확대의 전형
특이: "민자 성공모델"로 홍보되는 노선의 실체 = 교통량 안정 + 수입 실현율 62.5%까지 하락 —
      성공/실패의 기준이 축에 따라 정반대가 되는 사례
"""
import numpy as np
from backtest_plan_actual import loo_prior, pct_err

PLAN = {2022: 114145, 2023: 115090, 2024: 116033}   # 표5-11
ACT = {2022: 94030, 2023: 94621, 2024: 95299}
RATIOS = {2018: 0.875}                               # 정책브리핑 ✚비율만
# NABO 수입 표 (백만원): (협약, 징수)
REV = {2021: (70184, 56678), 2022: (73460, 54846), 2023: (77808, 54365),
       2024: (80920, 54492), 2025: (85096, 53206)}
LEN_KM = 22.9
OPEN_YEAR = 2009

def main():
    pri = loo_prior('용인-서울')
    mu, sd = pri['loo_mean'], pri['loo_sd']
    z = 1.2816
    p10r, p90r = mu - z * sd, mu + z * sd
    print(f"[LOO prior — 용인-서울 제외] 평균 {mu*100:.1f}% SD {sd:.4f} n={pri['loo_n']} "
          f"(밴드 {p10r*100:.0f}~{p90r*100:.0f}%)")

    print('\n' + '=' * 96)
    print('표① 교통량 — 협약(A) vs Forenode(B: LOO P50) vs 실측')
    print('=' * 96)
    print(f"{'연도':>5} {'연차':>4} {'협약':>9} {'실측':>9} {'오차A%':>8} {'B':>9} {'오차B%':>8} {'밴드':>5}")
    eA, eB, hits, n = [], [], 0, 0
    for y in sorted(PLAN):
        p, a = PLAN[y], ACT[y]
        b = p * mu
        ea, eb = pct_err(a, p), pct_err(a, b)
        hit = p10r <= a / p <= p90r
        hits += hit; n += 1
        eA.append(abs(ea)); eB.append(abs(eb))
        print(f"{y:>5} {y-OPEN_YEAR+1:>4} {p:>9,} {a:>9,} {ea:>7.1f}% {b:>9,.0f} {eb:>7.1f}% {'적중' if hit else '미적중':>4}")
    for y, r in sorted(RATIOS.items()):
        hit = p10r <= r <= p90r
        hits += hit; n += 1
        eA.append(abs((r - 1) * 100)); eB.append(abs((r / mu - 1) * 100))
        print(f"{y:>5} {y-OPEN_YEAR+1:>4} {'—':>9} {'—':>9} {(r-1)*100:>7.1f}% {'—':>9} {(r/mu-1)*100:>7.1f}% "
              f"{'적중' if hit else '미적중':>4}  ✚실현율만")
    print(f"\n  ▶ MAE ({n}개년): 협약(A) {np.mean(eA):.1f}% vs Forenode(B) {np.mean(eB):.1f}% · 밴드 적중 {hits}/{n}")

    print('\n표② 통행료수입 — 협약(A) vs 징수 (NABO, 백만원) · 수입 prior(62.33%) 비교')
    for y, (pa, aa) in sorted(REV.items()):
        rr = aa / pa
        ea, eb = (rr - 1) * 100, (rr / 0.6233 - 1) * 100
        print(f"  {y}  협약 {pa:>7,}  징수 {aa:>7,}  실현율 {rr*100:>5.1f}%  오차A {ea:+.1f}%  수입B {eb:+.1f}%")
    rrs = [aa / pa for pa, aa in REV.values()]
    print(f"  ▶ 수입 MAE: A {np.mean([abs((r-1)*100) for r in rrs]):.1f}% vs 수입 prior B "
          f"{np.mean([abs((r/0.6233-1)*100) for r in rrs]):.1f}% · '25 실현율 62.5% ≈ prior(62.33%) 정확 일치")

    print('\n[관찰]')
    print('  · "성공모델"의 두 얼굴: 교통량 82%대 안정 + 밴드 적중 vs 수입 실현율 80.8→62.5% 하락')
    print('    일로 — 성공/실패 판정이 축(교통량/수입)에 따라 정반대. 요금 동결(1,800 vs 협약')
    print('    2,200원)이 원인: 서수원평택과 동일 메커니즘의 반대편(교통량 미달+수입 더 미달)')
    print('  · ★수입 prior(62.33%)가 25년 실현율 62.5%와 정확히 일치 — 우연이지만 시사적:')
    print('    수입 prior는 "하락 종점"의 근사이지 연도별 예측이 아님 → 수입도 연차·요금 경로')
    print('    동적 모델 필요(하락 기울기 = 협약 인상 가정과 동결 현실의 누적 격차)')
    print('  · 회사 공개 실측(39,005→95,431→97,042)은 절대 수요 2.4배 성장 — 협약 눈높이(11.6만)가')
    print('    높았을 뿐: 마창·일산·범안로의 도시권 성장 패턴과 동일(용인 수지·광교 개발)')
    print('  · 손실보전 135→319억/년 확대(NABO) — "성공" 노선조차 미인상 보전이 연 300억대:')
    print('    재정 노출 제로 노선은 없다(서수원평택 관찰의 재확인)')
    print('  · 보류: 협약수익률(RR-24-12 54건 리스트·협약서 별표)·실측 10~17·19·21 연도별·')
    print('    2015 자금재조달 조건·수익률 재구성(DART 경수고속도로)')

if __name__ == '__main__':
    main()
